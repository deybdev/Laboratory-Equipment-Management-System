package Models;

public class ComputerCount {

    private String room;
    private int count;

    public void setRoom(String room) {
        this.room = room;
    }

    public void setCount(int count) {
        this.count = count;
    }

    public String getRoom() {
        return room;
    }

    public int getCount() {
        return count;
    }
}
